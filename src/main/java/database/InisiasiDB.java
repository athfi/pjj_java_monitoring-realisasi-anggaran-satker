package database;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

/**
 *
 * @author Hp
 */
public class InisiasiDB {

    private InisiasiDB() {
    }

    public static void setupSchema(Connection kon)
            throws SQLException {

        String sqlSatker = """
            CREATE TABLE IF NOT EXISTS satker (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                kode_satker VARCHAR(20) NOT NULL UNIQUE,
                nama_satker VARCHAR(120) NOT NULL
            )
            """;

        String sqlPagu = """
            CREATE TABLE IF NOT EXISTS pagu_akun (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                satker_id BIGINT NOT NULL,
                kode_akun VARCHAR(12) NOT NULL,
                nama_akun VARCHAR(120) NOT NULL,
                tahun_anggaran INT NOT NULL,
                deskripsi_kegiatan VARCHAR(150) NOT NULL,
                nilai_pagu DECIMAL(18,2) NOT NULL
                    CHECK (nilai_pagu >= 0),
                FOREIGN KEY (satker_id) REFERENCES satker(id)
            )
            """;

        String sqlRealisasi = """
            CREATE TABLE IF NOT EXISTS realisasi (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                pagu_id BIGINT NOT NULL,
                nomor_sp2d VARCHAR(40) NOT NULL UNIQUE,
                tanggal_realisasi DATE NOT NULL,
                nilai_realisasi DECIMAL(18,2) NOT NULL
                    CHECK (nilai_realisasi > 0),
                keterangan VARCHAR(250),
                FOREIGN KEY (pagu_id) REFERENCES pagu_akun(id)
            )
            """;

        try (Statement stmt = kon.createStatement()) {
            stmt.execute(sqlSatker);
            stmt.execute(sqlPagu);
            stmt.execute(sqlRealisasi);
        }
    }

    public static void seedData(Connection kon)
            throws SQLException {

        //TODO rubah agar pakai SatkerDAO untuk insert data satker
        String sql = """
        MERGE INTO satker (kode_satker, nama_satker)
        KEY (kode_satker)
        VALUES (?, ?)
        """;

        try (InputStream input = InisiasiDB.class.getResourceAsStream("/satker.csv")) {
            if (input == null) {
                throw new SQLException("File satker.csv tidak ditemukan di resources.");
            }

            try (BufferedReader reader = new BufferedReader(
                    new InputStreamReader(input, StandardCharsets.UTF_8))) {
                PreparedStatement ps = kon.prepareStatement(sql);
                String baris;
                boolean header = true;

                while ((baris = reader.readLine()) != null) {
                    //skip header
                    if (header) {
                        header = false;
                        continue;
                    }

                    if (baris.isBlank()) {
                        continue;
                    }

                    String[] data = baris.split(",", -1);

                    if (data.length < 2) {
                        throw new SQLException(
                                "Format baris satker.csv tidak valid: " + baris
                        );
                    }

                    ps.setString(1, data[0].trim());
                    ps.setString(2, data[1].trim());
                    ps.executeUpdate();
                }
            }
        } catch (IOException e) {
            throw new SQLException("Gagal membaca satker.csv.", e);
        }

        //TODO rubah agar pakai PaguAkunDAO untuk insert data pagu
        String cariSatker = """
        SELECT id FROM satker WHERE kode_satker = ?
        """;

        String cekPagu = """
            SELECT id FROM pagu_akun
            WHERE satker_id = ?
              AND kode_akun = ?
              AND tahun_anggaran = ?
              AND deskripsi_kegiatan = ?
            """;

        String insertPagu = """
            INSERT INTO pagu_akun (
                satker_id,
                kode_akun,
                nama_akun,
                tahun_anggaran,
                deskripsi_kegiatan,
                nilai_pagu
            )
            VALUES (?, ?, ?, ?, ?, ?)
            """;
        String filePagu = "kegiatan_pagu.csv";
        try (InputStream input = InisiasiDB.class.getResourceAsStream("/" + filePagu)) {
            if (input == null) {
                throw new SQLException("File " + filePagu + " tidak ditemukan di resources.");
            }

            try (BufferedReader reader = new BufferedReader(new InputStreamReader(input, StandardCharsets.UTF_8))) {

                PreparedStatement psSatker = kon.prepareStatement(cariSatker);
                PreparedStatement psCek = kon.prepareStatement(cekPagu);
                PreparedStatement psInsert = kon.prepareStatement(insertPagu);

                String baris;
                boolean header = true;

                while ((baris = reader.readLine()) != null) {
                    //skip header
                    if (header) {
                        header = false;
                        continue;
                    }
                    //skip jika kosong
                    if (baris.isBlank()) {
                        continue;
                    }

                    String[] data = baris.split(",", -1);
                    if (data.length < 6) {
                        throw new SQLException(
                                "Format baris " + filePagu + " tidak valid: " + baris
                        );
                    }
                    
                    //System.out.println(data[0]+"|"+data[1]+"|"+data[2]+"|"+data[3]+"|"+data[4]+"|"+data[5]);

                    String kodeSatker = data[0].trim();
                    String kodeAkun = data[1].trim();
                    String namaAkun = data[2].trim();
                    int tahun = Integer.parseInt(data[3].trim());
                    String kegiatan = data[4].trim();
                    BigDecimal nilaiPagu = new BigDecimal(data[5].trim());

                    // Cari ID satker berdasarkan kode satker
                    psSatker.setString(1, kodeSatker);
                    long satkerId;
                    try (ResultSet rs = psSatker.executeQuery()) {
                        if (!rs.next()) {
                            throw new SQLException("Satker tidak ditemukan: " + kodeSatker);
                        }
                        satkerId = rs.getLong("id");
                    }

                    // Jika data pagu sudah ada skip
                    psCek.setLong(1, satkerId);
                    psCek.setString(2, kodeAkun);
                    psCek.setInt(3, tahun);
                    psCek.setString(4, kegiatan);

                    try (ResultSet rs = psCek.executeQuery()) {
                        if (rs.next()) {
                            continue;
                        }
                    }

                    //input data
                    psInsert.setLong(1, satkerId);
                    psInsert.setString(2, kodeAkun);
                    psInsert.setString(3, namaAkun);
                    psInsert.setInt(4, tahun);
                    psInsert.setString(5, kegiatan);
                    psInsert.setBigDecimal(6, nilaiPagu);
                    psInsert.executeUpdate();

                }
            }
        } catch (IOException e) {
            throw new SQLException("Gagal membaca " + filePagu + ".", e);
        } catch (NumberFormatException e) {
            throw new SQLException(
                    "Format angka pada " + filePagu + " tidak valid.", e
            );
        }

    }

}
